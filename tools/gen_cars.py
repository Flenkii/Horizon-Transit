#!/usr/bin/env python3
"""Generates src/core/cars_data.c from the game's own car database (media/Stripped/gamedbRC.slt).

Every car of Forza Horizon 2's Data_Car table, by its media name (the name of its zip in media/cars,
which the mod reads from the driven car in game, as Gripline's logbook does):
  make  .... List_CarMake.IconPathBase (the logo's file name), a few spelled out
  model .... from the media name: "LAM_MiuraP400_67" -> "Miura P400", year '67
  kind ..... bus (PG_BUS_14), van (Transit, box truck), dream car (BaseCost >= 250000 CR or class S2 and up),
             sporty (BaseCost >= 60000 CR or class A and up), or normal
  group .... what kind of car it is, from FamilyBodyID (the Autoshow's groups): small car, hot hatch, saloon,
             sports car, supercar, classic, off-road; the big mixed group 1 by kind
  open ..... IsOpenCockpit (roadsters, open-top cars)

Usage:
  python tools/gen_cars.py <path to gamedbRC.slt> > src/core/cars_data.c
"""
import re
import sqlite3
import sys

MAKE_FIX = {
    "POR": "Porsche", "AlfaRomeo": "Alfa Romeo", "AstonMartin": "Aston Martin", "LandRover": "Land Rover",
    "ARI": "Ariel", "BOW": "Bowler", "CAT": "Caterham", "DON": "Donkervoort", "HEN": "Hennessey",
    "LOC": "Local Motors", "ROB": "Robby Gordon", "TER": "Terradyne", "TES": "Tesla", "ULT": "Ultima",
    "PG": "", "Mercedes": "Mercedes-Benz",
}
BUS = {"PG_BUS_14"}
# FamilyBodyID -> group (TS_GROUP_ in cars.h)
GROUPS = {
    2: "SMALL", 3: "SMALL", 4: "SMALL", 41: "SMALL",
    15: "HATCH", 24: "HATCH", 34: "HATCH", 30: "SPORTS",
    18: "SALOON",
    7: "SPORTS", 17: "SPORTS", 22: "SPORTS", 29: "SPORTS", 31: "SPORTS", 12: "SPORTS", 13: "SPORTS",
    23: "SUPER", 26: "SUPER", 27: "SUPER", 42: "SUPER", 43: "SUPER", 44: "SUPER", 45: "SUPER",
    6: "CLASSIC", 9: "CLASSIC", 10: "CLASSIC", 11: "CLASSIC", 20: "CLASSIC", 36: "CLASSIC", 38: "CLASSIC",
    39: "OFFROAD",
}
VANS = {"FOR_Transit_11", "FOR_TransitSSV_11", "PG_BoxTruck_14"}


def model_of(media):
    parts = media.split("_")
    middle = "_".join(parts[1:-1]) if len(parts) >= 3 else (parts[1] if len(parts) > 1 else media)
    middle = re.sub(r"(?<=[a-z])(?=[A-Z])", " ", middle)  # MiuraP400 -> Miura P400
    middle = re.sub(r"(?<=[0-9])(?=[A-Z][a-z])", " ", middle)  # 918Spyder -> 918 Spyder
    middle = middle.replace("_", " ")
    if media == "PG_BUS_14":
        return "Bus"
    if media == "PG_BoxTruck_14":
        return "Box Truck"
    return middle


def main():
    db = sqlite3.connect("file:%s?mode=ro" % sys.argv[1], uri=True)
    makes = {row[0]: row[1] for row in db.execute("SELECT ID, IconPathBase FROM List_CarMake")}
    rows = db.execute("SELECT MediaName, MakeID, Year, BaseCost, ClassID, FamilyBodyID, IsOpenCockpit FROM Data_Car "
                      "ORDER BY MediaName").fetchall()
    out = ["/* Generated by tools/gen_cars.py from the game's database (Data_Car, List_CarMake). Do not edit by hand. */",
           '#include "cars.h"', "", "const TsCarInfo ts_cars[] = {"]
    for media, make_id, year, cost, class_id, body, is_open in rows:
        if media.upper() == "NUL_CAR_00":
            continue
        make = makes.get(make_id, "")
        make = MAKE_FIX.get(make, make)
        if media in BUS:
            kind = "TS_CAR_BUS"
        elif media in VANS:
            kind = "TS_CAR_VAN"
        elif cost >= 250000 or class_id >= 5:
            kind = "TS_CAR_DREAM"
        elif cost >= 60000 or class_id >= 3:
            kind = "TS_CAR_SPORTY"
        else:
            kind = "TS_CAR_NORMAL"
        group = GROUPS.get(body)
        if kind == "TS_CAR_BUS":
            group = "BUS"
        elif media in VANS:
            group = "OFFROAD"
        elif not group:
            group = "SUPER" if kind == "TS_CAR_DREAM" else "SPORTS" if kind == "TS_CAR_SPORTY" else "SMALL"
        out.append('    {"%s", "%s", "%s", %d, %d, %s, TS_GROUP_%s, %d},' % (media, make, model_of(media), year or 0, cost or 0,
                                                                         kind, group, 1 if is_open else 0))
    out.append("};")
    out.append("const unsigned ts_car_count = sizeof(ts_cars) / sizeof(ts_cars[0]);")
    sys.stdout.buffer.write(("\n".join(out) + "\n").encode("utf-8"))


if __name__ == "__main__":
    main()
